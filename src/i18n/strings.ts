const DICTS: Partial<Record<Lang, Dict>> = {en, fr, es};

/** The translated blocks, for the coverage test. */
export const BLOCKS = {fr, es} as const;
export const KEYS = Object.keys(en) as Key[];

export function isLang(x: unknown): x is Lang {
  return typeof x === 'string' && (LANGS as readonly string[]).includes(x);
}

/** One string, in one language, with `{placeholders}` filled. An unknown placeholder stays visible. */
export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const s = DICTS[lang]?.[key] ?? en[key];
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}
